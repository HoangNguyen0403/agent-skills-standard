#!/usr/bin/env python3
"""Task4 staged generator runner.

Guarded, single-purpose helper. It:
  1. validates the scratch stage realpath (Under /private/tmp/cad-task4-stage.*),
  2. refuses to run inside the active checkout,
  3. removes only the exact scratch mirror targets needed so the ownership
     writer treats the regenerated bytes as `added` (no-lockfile trap),
  4. runs the documented generators with cwd=stage, full log capture and exact
     exit codes.

It never writes outside the stage except the two log files and stage-run.json
under artifacts/context-aware-delegation/final-evidence/.
"""

import json
import os
import pathlib
import shutil
import subprocess
import sys
import time

REPO = pathlib.Path(__file__).resolve().parents[3]
EVIDENCE = REPO / "artifacts" / "context-aware-delegation" / "final-evidence"

CLEANUP_TARGETS = [
    ".agents/skills/common/common-subagent-driven-development",
    ".github/skills/common/common-subagent-driven-development",
    ".codex/skills/common/common-subagent-driven-development",
    ".claude/skills/common/common-subagent-driven-development",
    ".agents/skills/common/common-task-complexity-routing",
    ".github/skills/common/common-task-complexity-routing",
    ".codex/skills/common/common-task-complexity-routing",
    ".claude/skills/common/common-task-complexity-routing",
    ".agents/skills/common/_INDEX.md",
    ".github/skills/common/_INDEX.md",
    ".codex/skills/common/_INDEX.md",
    ".claude/skills/common/_INDEX.md",
]

GENERATORS = [
    ("generate-indices", ["scripts/generate-indices.ts"], "stage-yij7fr-generate-indices.log"),
    ("generate-capabilities", ["scripts/generate-capabilities-doc.ts"], "stage-yij7fr-generate-capabilities.log"),
]


def fail(message: str) -> "None":
    print(f"REFUSED: {message}", file=sys.stderr)
    sys.exit(2)


def main() -> None:
    if len(sys.argv) != 2:
        fail("usage: run-stage-generator.py <stage-path>")
    stage = pathlib.Path(sys.argv[1])
    if not stage.exists():
        fail(f"stage missing: {stage}")
    stage_real = stage.resolve()
    if not str(stage_real).startswith("/private/tmp/cad-task4-stage.") and not str(
        stage_real
    ).startswith("/tmp/cad-task4-stage."):
        fail(f"stage realpath is not a verified scratch prefix: {stage_real}")
    repo_real = REPO.resolve()
    if stage_real == repo_real or repo_real in stage_real.parents:
        fail("stage resolves inside the active checkout")
    if not (stage_real / "scripts" / "generate-indices.ts").exists():
        fail("stage is not an authoring checkout copy")

    removed = []
    absent = []
    for rel in CLEANUP_TARGETS:
        target = (stage_real / rel).resolve()
        if stage_real not in target.parents:
            fail(f"cleanup target escapes stage: {rel}")
        if not os.path.lexists(target):
            absent.append(rel)
            continue
        if target.is_dir() and not target.is_symlink():
            shutil.rmtree(target)
        else:
            target.unlink()
        removed.append(rel)

    rtk = shutil.which("rtk")
    node = shutil.which("node") or fail("node not found")
    node_version = subprocess.run(
        [node, "--version"], capture_output=True, text=True, check=True
    ).stdout.strip()

    runs = []
    for name, script, log_name in GENERATORS:
        command = (["rtk", "proxy", "node", "--import", "tsx"] if rtk else [node, "--import", "tsx"]) + script
        started = time.strftime("%Y-%m-%dT%H:%M:%S%z")
        proc = subprocess.run(command, cwd=stage_real, capture_output=True, text=True)
        finished = time.strftime("%Y-%m-%dT%H:%M:%S%z")
        log_text = (
            f"$ (cd {stage_real} && {' '.join(command)})\n"
            f"started: {started}\nfinished: {finished}\n"
            f"exit: {proc.returncode}\n\n--- stdout ---\n{proc.stdout}\n--- stderr ---\n{proc.stderr}\n"
        )
        (EVIDENCE / log_name).write_text(log_text, encoding="utf-8")
        runs.append(
            {
                "name": name,
                "command": command,
                "rtk_available": bool(rtk),
                "cwd": str(stage_real),
                "started": started,
                "finished": finished,
                "exit": proc.returncode,
                "stdout_lines": len(proc.stdout.splitlines()),
                "stderr_lines": len(proc.stderr.splitlines()),
                "log": str((EVIDENCE / log_name).relative_to(REPO)),
            }
        )

    record = {
        "helper": "artifacts/context-aware-delegation/final-evidence/run-stage-generator.py",
        "stage_realpath": str(stage_real),
        "active_realpath": str(repo_real),
        "node_version": node_version,
        "rtk_available": bool(rtk),
        "cleanup_removed": removed,
        "cleanup_already_absent": absent,
        "runs": runs,
    }
    (EVIDENCE / "stage-run.json").write_text(
        json.dumps(record, indent=2) + "\n", encoding="utf-8"
    )
    print(json.dumps(record, indent=2))
    if any(run["exit"] != 0 for run in runs):
        sys.exit(1)


if __name__ == "__main__":
    main()
