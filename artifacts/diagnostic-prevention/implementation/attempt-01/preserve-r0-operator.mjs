import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
const base = path.resolve('artifacts/diagnostic-prevention/implementation/attempt-01');
const bytes = await fs.readFile(path.join(base, 'restore-interrupted-root.mjs'));
const sha256 = value => createHash('sha256').update(value).digest('hex');
const expected = '7022e9d3546dd32654d3c14e69480a907673cd91e2fec716abe7d0f6f9fb0c28';
if (sha256(bytes) !== expected) throw new Error('Frozen operator identity changed');
const output = path.join(base, 'restore-interrupted-root-before-correction-01.source');
await fs.writeFile(output, bytes, { flag: 'wx' });
if (sha256(await fs.readFile(output)) !== expected) throw new Error('Snapshot readback mismatch');
await fs.chmod(output, 0o444);
console.log(JSON.stringify({ path: path.relative(process.cwd(), output), sha256: expected, bytes: bytes.length, kind: 'R0_STATIC_REVIEW_FAILED_SOURCE_NOT_EXECUTED_RED' }));
